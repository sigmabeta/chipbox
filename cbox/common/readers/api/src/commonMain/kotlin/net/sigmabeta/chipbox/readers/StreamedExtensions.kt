/**
 * Whether [extension] is a streamed-audio format the vendored vgmstream build can open
 * (lowercase or not, without a leading dot).
 *
 * Only meaningful to distinguish "known but unreadable" from "arbitrary unknown file": callers
 * must check for a registered [Reader] first — several extensions here (adx, brstm, vgm, …) are
 * served by dedicated Kotlin readers.
 */
fun isKnownStreamedExtension(extension: String): Boolean =
    extension.lowercase() in StreamedExtensions.ALL
